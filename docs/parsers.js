// Lockfile parsers. Each returns { kind, ecosystem, packages: [{name, version}], extra: {ruby?} } or null.
// Everything runs in the browser; nothing here talks to the network.
(function () {
  const uniq = (list) => { const seen = new Set(); return list.filter((p) => { const k = p.name + '@' + p.version; if (!p.name || !p.version || seen.has(k)) return false; seen.add(k); return true; }); };
  const tryJSON = (t) => { try { return JSON.parse(t); } catch { return null; } };

  function npmLock(t) {
    const j = tryJSON(t); if (!j || !(j.packages || j.dependencies) || !('lockfileVersion' in j)) return null;
    const out = [];
    if (j.packages) for (const [path, p] of Object.entries(j.packages)) {
      if (!path || !p.version || p.link) continue;
      const name = p.name || path.slice(path.lastIndexOf('node_modules/') + 13);
      out.push({ name, version: p.version });
    } else (function walk(deps) { for (const [name, p] of Object.entries(deps || {})) { if (p.version) out.push({ name, version: p.version }); walk(p.dependencies); } })(j.dependencies);
    return { kind: 'package-lock.json', ecosystem: 'npm', packages: out };
  }

  function yarnLock(t) {
    if (!/^# yarn lockfile v1|^__metadata:/m.test(t) && !/^"?[@\w][^\n]*@[^\n]*:\n\s+version:? "?/m.test(t)) return null;
    const out = [];
    for (const block of t.split(/\n(?=\S)/)) {
      const head = block.split('\n')[0].replace(/:$/, '');
      const m = block.match(/\n\s+version:? "?([^"\n]+)"?/); if (!m) continue;
      const first = head.split(',')[0].trim().replace(/^"|"$/g, '');
      const at = first.lastIndexOf('@'); if (at <= 0) continue;
      let name = first.slice(0, at); name = name.replace(/@npm$/, '');
      if (/@(workspace|patch|link|portal|file):/.test(first)) continue;
      out.push({ name, version: m[1] });
    }
    return out.length ? { kind: 'yarn.lock', ecosystem: 'npm', packages: out } : null;
  }

  function pnpmLock(t) {
    if (!/^lockfileVersion:/m.test(t)) return null;
    const out = [];
    const sec = t.split(/\n(?=packages:|snapshots:)/).find((s) => s.startsWith('packages:')) || t;
    for (const m of sec.matchAll(/^ {2}'?\/?((?:@[^/@\s]+\/)?[^@\s:'(]+)[@/]([0-9][^:'(\s]*)/gm)) out.push({ name: m[1], version: m[2] });
    return out.length ? { kind: 'pnpm-lock.yaml', ecosystem: 'npm', packages: out } : null;
  }

  function gemfileLock(t) {
    if (!/^GEM\n|^\s+specs:/m.test(t) || !/^ {4}\S+ \(/m.test(t)) return null;
    const out = [];
    for (const m of t.matchAll(/^ {4}([A-Za-z0-9_.\-]+) \(([0-9][^)\s-]*)(?:-[^)]*)?\)$/gm)) out.push({ name: m[1], version: m[2] });
    const r = t.match(/^RUBY VERSION\n\s+ruby (\d+\.\d+\.\d+)/m);
    return { kind: 'Gemfile.lock', ecosystem: 'RubyGems', packages: out, extra: r ? { ruby: r[1] } : {} };
  }

  function tomlPackages(t) {   // Cargo.lock, poetry.lock, uv.lock: [[package]] name = "x" version = "y"
    const out = [];
    for (const block of t.split(/^\[\[package\]\]/m).slice(1)) {
      const n = block.match(/^name = "([^"]+)"/m), v = block.match(/^version = "([^"]+)"/m);
      if (n && v) out.push({ name: n[1], version: v[1] });
    }
    return out;
  }
  function cargoLock(t) {
    if (!/@generated by Cargo|^\[\[package\]\][\s\S]*?source = "registry\+https:\/\/github.com\/rust-lang\/crates.io-index"/m.test(t)) return null;
    return { kind: 'Cargo.lock', ecosystem: 'crates.io', packages: tomlPackages(t) };
  }
  function pyToml(t) {
    if (!/^\[\[package\]\]/m.test(t)) return null;
    const kind = /@generated by Poetry|^\[metadata\]/m.test(t) ? 'poetry.lock' : /^requires-python|^revision = /m.test(t) ? 'uv.lock' : 'poetry.lock';
    return { kind, ecosystem: 'PyPI', packages: tomlPackages(t) };
  }
  function pipfileLock(t) {
    const j = tryJSON(t); if (!j || !j._meta || !(j.default || j.develop)) return null;
    const out = [];
    for (const sec of [j.default || {}, j.develop || {}]) for (const [name, p] of Object.entries(sec)) if (p.version) out.push({ name, version: p.version.replace(/^==/, '') });
    return { kind: 'Pipfile.lock', ecosystem: 'PyPI', packages: out };
  }
  function requirements(t) {
    const lines = t.split('\n').map((l) => l.replace(/#.*/, '').trim()).filter(Boolean);
    const pins = lines.map((l) => l.match(/^([A-Za-z0-9][A-Za-z0-9._\-]*)(?:\[[^\]]*\])?\s*===?\s*([0-9][^\s;\\]*)/)).filter(Boolean);
    if (!pins.length || pins.length < lines.filter((l) => !l.startsWith('-')).length * 0.5) return null;
    return { kind: 'requirements.txt', ecosystem: 'PyPI', packages: pins.map((m) => ({ name: m[1], version: m[2] })) };
  }
  function goSum(t) {
    const ms = [...t.matchAll(/^([^\s]+\.[^\s]+\/[^\s]+) v([0-9][^\s/]*)(?:\/go\.mod)? h1:/gm)];
    const req = ms.length ? ms : [...t.matchAll(/^\s*([^\s]+\.[^\s]+\/[^\s]+) v([0-9][^\s]*)(?:\s*\/\/ indirect)?$/gm)];
    if (!req.length) return null;
    return { kind: ms.length ? 'go.sum' : 'go.mod', ecosystem: 'Go', packages: req.map((m) => ({ name: m[1], version: m[2].replace(/\+incompatible$/, '') })) };
  }
  function composerLock(t) {
    const j = tryJSON(t); if (!j || !Array.isArray(j.packages) || !('content-hash' in j)) return null;
    return { kind: 'composer.lock', ecosystem: 'Packagist', packages: [...j.packages, ...(j['packages-dev'] || [])].map((p) => ({ name: p.name, version: String(p.version).replace(/^v/, '') })) };
  }

  const ORDER = [npmLock, composerLock, pipfileLock, gemfileLock, cargoLock, pnpmLock, yarnLock, pyToml, goSum, requirements];
  window.parseLockfile = function (text, filename = '') {
    const f = filename.toLowerCase();
    const byName = { 'package-lock.json': npmLock, 'npm-shrinkwrap.json': npmLock, 'yarn.lock': yarnLock, 'pnpm-lock.yaml': pnpmLock, 'gemfile.lock': gemfileLock,
      'cargo.lock': cargoLock, 'poetry.lock': pyToml, 'uv.lock': pyToml, 'pipfile.lock': pipfileLock, 'go.sum': goSum, 'go.mod': goSum, 'composer.lock': composerLock };
    const fns = byName[f] ? [byName[f], ...ORDER] : f.endsWith('.txt') ? [requirements, ...ORDER] : ORDER;
    for (const fn of fns) { const r = fn(text); if (r && r.packages.length) { r.packages = uniq(r.packages); return r; } }
    return null;
  };
})();
